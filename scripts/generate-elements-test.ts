/**
 * Fetches latest block element documentation from Slack and generates a test file to compare that
 * with the local types.
 */
import { resolve } from 'node:path'

const blockElements = (await cachedRequest('https://docs.slack.dev/block-elements.json').then((r) =>
	JSON.parse(r),
)) as {
	name: string
	description: string
	'available-in-surfaces': string[]
	'works-with-blocks': string[]
}[]

console.log(`// autogenerated by scripts/generate-elements-test.ts at ${new Date().toISOString()}`)
console.log()
console.log("import type { RichTextBlock } from '../src/types/blocks/blocks'")
console.log("import type { CheckboxOptionObject } from '../src/types/blocks/elements'")
console.log(
	"import type { ConfirmationDialogObject, PlainTextObject, PlainTextOptionObject } from '../src/types/blocks/objects'",
)
console.log("import type { DispatchActionConfig } from '@slack/types'")
console.log("import { describe, expectTypeOf, it } from 'bun:test'")
console.log()
console.log("describe('block kit elements (autogenerated)', () => {")

const fieldTypes = new Set()
const fieldRequrieds = new Set()

const fieldTypeMap = new Map([
	['String', 'string'],
	['Boolean', 'boolean'],
	// ['Object', 'any'],
	['String[]', 'string[]'],
	// ['Object[]', 'any[]'],
	['Number', 'number'],
	['Integer', 'number'],
	[
		'[Richtext](https://docs.slack.dev/reference/block-kit/blocks/rich-text-block.md)',
		'RichTextBlock',
	],
])

const fieldTypeOverrides = new Map([
	['button;style', "'danger' | 'primary'"],
	['button;text', 'PlainTextObject'],
	['checkboxes;options', 'CheckboxOptionObject[]'],
	['checkboxes;initial_options', 'CheckboxOptionObject[]'],
	[
		'feedback_buttons;positive_button',
		'{ text: PlainTextObject, value: string, accessibility_label?: string}',
	],
	[
		'feedback_buttons;negative_button',
		'{ text: PlainTextObject, value: string, accessibility_label?: string}',
	],
	['icon_button;text', 'PlainTextObject'],
	['image;slack_file', '{ url: string } | { id: string }'],
	['overflow;options', 'PlainTextOptionObject[]'],
	['radio_buttons;options', 'CheckboxOptionObject[]'],
	['radio_buttons;initial_option', 'CheckboxOptionObject'],
	['workflow_button;text', 'PlainTextObject'],
	['workflow_button;style', "'danger' | 'primary'"],
	[
		'workflow_button;workflow',
		'{ trigger: { url: string, customizable_input_parameters?: { name: string, value: string }[] } }',
	],

	['confirm', 'ConfirmationDialogObject'],
	['placeholder', 'PlainTextObject'],
	['dispatch_action_config', 'DispatchActionConfig'],
])

const requiredOverrides = new Map([
	['rich_text_input;action_id', false],
	['workflow_button;action_id', false],
])

const typeStringOverrides = new Map([
	['Date picker', 'datepicker'],
	['Datetime picker', 'datetimepicker'],
	['Email input', 'email_text_input'],
	['Overflow menu', 'overflow'],
	['Radio button group', 'radio_buttons'],
	['Time picker', 'timepicker'],
	['URL input', 'url_text_input'],
])

const skipTypeCheck = new Set(['image'])

for (const { name, 'works-with-blocks': worksWith } of blockElements) {
	if (['Task card', 'Rich text'].includes(worksWith.join(','))) continue

	const slug = name.toLowerCase().replace(/[^0-9A-Z]+/gi, '-') + '-element'
	const page = await cachedRequest(
		`https://docs.slack.dev/reference/block-kit/block-elements/${slug}.md`,
	)

	const typeString =
		typeStringOverrides.get(name) ?? name.toLowerCase().replace(/[^0-9A-Z]+/gi, '_')
	const tsName =
		typeString
			.replace(/(?<=^|_)url(?=$|_)/g, 'URL')
			.replace(/(?:_|^)([a-z])/gi, (_, c) => c.toUpperCase()) + 'Element'

	// find fields section

	const paragraphs = page.split(/\n{2,}/g)

	const index = paragraphs.indexOf('## Fields {#fields}')
	if (index < 0) {
		console.warn('fields section not found in', slug)
		continue
	}

	console.log(`\tdescribe('${name.toLowerCase()}', () => {`)
	console.log(`\t\ttype Element = import('../src/types/blocks/elements').${tsName}`)
	console.log(`\t\ttype Flat = { [K in keyof Element]: Element[K] }`)
	console.log(`\t\tinterface DocType {`)

	for (let i = index + 5; i + 3 < paragraphs.length && paragraphs[i]!.startsWith('`'); i += 4) {
		const fieldName = paragraphs[i]!.replace(/`/g, '').trim()
		const fieldType = paragraphs[i + 1]!.replace(/\\\[/g, '[')
			.replace(/\\\]/g, ']')
			.replace(/\s+/g, '')
			.replace(/^Array$/, 'String[]')
		const fieldRequired = paragraphs[i + 3]!.trim()

		const isRequired =
			requiredOverrides.get(`${typeString};${fieldName}`) ?? fieldRequired === 'Required'

		const tsType =
			fieldName === 'type'
				? `'${typeString}'`
				: (fieldTypeOverrides.get(`${typeString};${fieldName}`) ??
					fieldTypeOverrides.get(fieldName) ??
					fieldTypeMap.get(fieldType) ??
					fieldType)

		if (tsType === fieldType) {
			console.error(typeString, fieldName, fieldType, 'has no type')
		}

		// console.log('-', fieldName, '-', fieldType, `(${fieldRequired})`)
		console.log(`\t\t\t${fieldName}${!isRequired ? '?' : ''}: ${tsType}`)

		fieldTypes.add(fieldType)
		fieldRequrieds.add(fieldRequired)
	}

	console.log('\t\t}')
	if (!skipTypeCheck.has(typeString)) {
		console.log("\t\tit('matches type in slack docs', () => {")
		console.log(`\t\t\texpectTypeOf<Flat>().branded.toEqualTypeOf<DocType>()`)
		console.log('\t\t})')
	}
	console.log('\t})')

	// console.log()
}

console.log('})')

async function cachedRequest(input: string, init?: RequestInit) {
	const url = new URL(input)
	const path = url.pathname.substring(1)
	const cacheFile = Bun.file(resolve('scripts/tmp_cache', url.host, path))

	if (await cacheFile.exists()) {
		return await cacheFile.text()
	}

	const resp = await fetch(url, init)
	if (!resp.ok) {
		throw new Error(`Failed to fetch ${url}: ${resp.status}\n${await resp.text()}`)
	}

	const text = await resp.text()

	Bun.write(cacheFile, text, { createPath: true })

	return text
}
