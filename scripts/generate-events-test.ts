import { cachedRequest } from './utils'

const SKIP_EVENTS = [
	'app_rate_limited',
	'url_verification',
	'presence_query',
	'presence_sub',

	// does not seem to exist as far as i know
	'channel_posting_permissions',
	'file_comment_added',
	'file_comment_edited',
]

const eventList = (
	JSON.parse(await cachedRequest('https://docs.slack.dev/reference/events.json')) as {
		name: string
		description: string
		scopes?: string[]
		APIs: string[]
	}[]
).filter((e) => {
	if (SKIP_EVENTS.includes(e.name)) return false
	if (e.name.includes('.')) {
		if (!e.name.startsWith('message.')) {
			throw new Error(`Unknown event name: ${e.name}`)
		}
		return false
	}
	return true
})

const standardEvents = eventList.filter((e) => e.APIs.includes('Events'))
const rtmEvents = eventList.filter((e) => e.APIs.includes('RTM'))

console.log(`// autogenerated by scripts/generate-events-test.ts at ${new Date().toISOString()}`)
console.log()
console.log('import type {')
for (const event of eventList) {
	console.log(`\t${className(event.name)},`)
}
console.log(`\tStandardEvent,`)
console.log(`\tRTMEvent,`)
console.log("} from '../src/types/events'")
console.log("import { describe, expectTypeOf, it } from 'bun:test'")
console.log()
console.log("describe('events (autogenerated)', () => {")

console.log("\tit('has the correct standard api types', () => {")
const standardUnion = standardEvents.map((e) => className(e.name)).join(' | ')
console.log(`\t\texpectTypeOf<StandardEvent>().toEqualTypeOf<${standardUnion}>()`)
console.log('\t})')

console.log()

console.log("\tit('has the correct rtm api types', () => {")
const rtmUnion = rtmEvents.map((e) => className(e.name)).join(' | ')
console.log(`\t\texpectTypeOf<RTMEvent>().toEqualTypeOf<${rtmUnion}>()`)
console.log('\t})')
console.log('})')

function className(name: string) {
	return (
		name.charAt(0).toUpperCase() +
		name.substring(1).replace(/_([a-z])/g, (_, c) => c.toUpperCase()) +
		'Event'
	)
		.replace(/Id(?=[A-Z])/g, 'ID')
		.replace(/Url(?=[A-Z])/g, 'URL')
		.replace(/^Im(?=[A-Z])/, 'IM')
		.replace(/^Dnd(?=[A-Z])/, 'DND')
}
