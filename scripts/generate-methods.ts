import { cachedRequest, generateInterface } from './utils'

// arg.name -> type
const argTypeMap = new Map([['channel_ids', 'string[]']])

// slack type -> type
const typeMap = new Map([
	['integer', 'number'],
	['array', 'unknown[]'],
])

const requiredResponseKeys = new Set([''])

const removeExamplePrefixes = [`{"url": "","description": "Typical success response","example": `]

const methods = (await cachedRequest('https://docs.slack.dev/reference/methods.json').then((r) =>
	JSON.parse(r),
)) as {
	name: string
	description: string
	family: [string]
}[]

console.log('// generated by scripts/generate-methods.ts at', new Date().toISOString())
console.log()

const typedMethods = new Set<string>()

for (const { name } of methods) {
	const page = await cachedRequest(`https://docs.slack.dev/reference/methods/${name}.md`)

	// TODO: parse scopes from frontmatter

	const args = Array.from(page.matchAll(/\*\*`(.+)`\*\*`(.+)`(Required|Optional)/g), (m) => ({
		name: m[1]!,
		type: m[2]!,
		required: m[3] === 'Required',
	}))

	const exampleMatch = page.match(/## Response {#response}\n\n(?:#### [^\n]+\n\n)?```\n(.+?)\n```/s)
	let exampleJson
	if (!exampleMatch) {
		console.error(`no response type for ${name}`)
		exampleJson = '{}'
	} else {
		exampleJson = exampleMatch[1]!

		for (const prefix of removeExamplePrefixes) {
			if (exampleJson.startsWith(prefix)) {
				exampleJson = exampleJson.substring(prefix.length)
			}
		}
	}

	let example
	try {
		example = JSON.parse(exampleJson)
	} catch (e) {
		console.error(`failed to parse response type for ${name}`, e)
		continue
	}
	if (typeof example === 'string') example = {}
	delete example.ok

	console.log(`export interface ${tsName(name)}Params {`)
	for (const arg of args) {
		if (arg.name === 'token') continue

		const type = argTypeMap.get(arg.name) ?? typeMap.get(arg.type) ?? arg.type
		console.log(`\t"${arg.name}": ${type}`)
	}
	console.log('}')

	console.log(generateInterface(example, `${tsName(name)}Response`, { isOptional: () => true }))
	console.log()

	typedMethods.add(name)
}

console.log('export interface DocumentedMethodMap {')
for (const { name } of methods) {
	if (!typedMethods.has(name)) continue
	console.log(`\t"${name}": { params: ${tsName(name)}Params; response: ${tsName(name)}Response }`)
}
console.log('}')

function tsName(name: string) {
	return name[0]?.toUpperCase() + name.replace(/\.([a-z])/g, (_, c) => c.toUpperCase()).substring(1)
}
